-- Exclusivo del modo de demostración H2. Nunca se ejecuta en Supabase.
CREATE TABLE IF NOT EXISTS personal (
 id_personal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ci VARCHAR(30) NOT NULL UNIQUE, nombres VARCHAR(100) NOT NULL, apellidos VARCHAR(100) NOT NULL,
 cargo VARCHAR(30) NOT NULL CHECK(cargo IN ('Administrador','Despachador')),
 telefono VARCHAR(30), activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS tipo_combustible (
 id_combustible INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE, unidad_medida VARCHAR(30) NOT NULL DEFAULT 'Litros'
);
CREATE TABLE IF NOT EXISTS historial_precio (
 id_historial_precio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_combustible INTEGER NOT NULL REFERENCES tipo_combustible,
 precio_litro NUMERIC(12,2) NOT NULL CHECK(precio_litro>0),
 fecha_inicio TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_fin TIMESTAMP WITH TIME ZONE, resolucion_anh VARCHAR(100),
 CHECK(fecha_fin IS NULL OR fecha_fin>fecha_inicio)
);
CREATE TABLE IF NOT EXISTS tanque (
 id_tanque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo_tanque VARCHAR(30) NOT NULL UNIQUE,
 capacidad_maxima_litros NUMERIC(15,3) NOT NULL CHECK(capacidad_maxima_litros>0),
 stock_actual_litros NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK(stock_actual_litros>=0),
 id_combustible INTEGER NOT NULL REFERENCES tipo_combustible,
 CHECK(stock_actual_litros<=capacidad_maxima_litros)
);
CREATE TABLE IF NOT EXISTS isla (
 id_isla INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero_isla INTEGER NOT NULL UNIQUE, descripcion VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS manguera (
 id_manguera INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo_manguera VARCHAR(30) NOT NULL UNIQUE, lado CHAR(1) NOT NULL CHECK(lado IN ('A','B')),
 id_isla INTEGER NOT NULL REFERENCES isla, id_tanque INTEGER NOT NULL REFERENCES tanque
);
CREATE TABLE IF NOT EXISTS turno (
 id_turno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fecha DATE NOT NULL,
 franja VARCHAR(20) NOT NULL CHECK(franja IN ('Mañana','Tarde','Noche')),
 estado VARCHAR(20) NOT NULL DEFAULT 'Abierto' CHECK(estado IN ('Abierto','Cerrado')),
 total_recaudado_cierre NUMERIC(15,2) DEFAULT 0 CHECK(total_recaudado_cierre>=0),
 id_administrador INTEGER NOT NULL REFERENCES personal
);
CREATE TABLE IF NOT EXISTS asignacion_turno_manguera (
 id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_turno INTEGER NOT NULL REFERENCES turno,
 id_despachador INTEGER NOT NULL REFERENCES personal, id_manguera INTEGER NOT NULL REFERENCES manguera,
 lectura_inicial NUMERIC(15,3) NOT NULL CHECK(lectura_inicial>=0),
 lectura_final NUMERIC(15,3), litros_calibracion NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK(litros_calibracion>=0),
 UNIQUE(id_turno,id_manguera), CHECK(lectura_final IS NULL OR lectura_final>=lectura_inicial)
);
CREATE TABLE IF NOT EXISTS cliente (
 id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nit_ci VARCHAR(30) NOT NULL UNIQUE, razon_social VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS venta (
 id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nro_factura VARCHAR(50) NOT NULL UNIQUE, fecha_hora TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 placa_vehiculo VARCHAR(30) NOT NULL, litros_vendidos NUMERIC(15,3) NOT NULL CHECK(litros_vendidos>0),
 precio_unitario_aplicado NUMERIC(12,2) NOT NULL CHECK(precio_unitario_aplicado>0),
 monto_total NUMERIC(15,2) NOT NULL CHECK(monto_total>0),
 metodo_pago VARCHAR(20) NOT NULL CHECK(metodo_pago IN ('Efectivo','QR','Tarjeta')),
 id_cliente INTEGER NOT NULL REFERENCES cliente, id_asignacion INTEGER NOT NULL REFERENCES asignacion_turno_manguera
);
CREATE TABLE IF NOT EXISTS recepcion_cisterna (
 id_recepcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha_hora TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 nro_guia_remision VARCHAR(50) NOT NULL, litros_recibidos NUMERIC(15,3) NOT NULL CHECK(litros_recibidos>0),
 id_tanque INTEGER NOT NULL REFERENCES tanque, id_administrador INTEGER NOT NULL REFERENCES personal
);
CREATE TABLE IF NOT EXISTS eess_demo_version (version INTEGER PRIMARY KEY);
